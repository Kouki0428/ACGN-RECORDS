/** 应用内分类 → Bangumi subject type（用于挑选关联/职位标签集合） */
export function categoryToBgmType(category?: string): number {
  switch (category) {
    case 'anime': return 2
    case 'light_novel':
    case 'manga': return 1
    case 'galgame': return 4
    default: return 2
  }
}
